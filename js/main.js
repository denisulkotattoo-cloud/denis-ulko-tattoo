const waNumber = "50664303209";

function applyLang(lang) {
  const t = dict[lang] || dict.en;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i]").forEach((el) => {
    const key = el.getAttribute("data-i");
    if (!t[key]) return;
    if (el.dataset.iHtml === "1") {
      el.innerHTML = t[key].replace(/\n/g, "<br>");
    } else {
      el.textContent = t[key];
    }
  });
  document.querySelectorAll(".lang button").forEach((b) => {
    b.classList.toggle("is-on", b.dataset.lang === lang);
  });
  const msg = encodeURIComponent(t.waText);
  document.querySelectorAll("[data-wa]").forEach((a) => {
    a.href = `https://wa.me/${waNumber}?text=${msg}`;
  });
  localStorage.setItem("du-lang", lang);
}

document.querySelectorAll(".lang button").forEach((b) => {
  b.addEventListener("click", () => applyLang(b.dataset.lang));
});
applyLang(localStorage.getItem("du-lang") || "en");

const toggle = document.querySelector(".menu-toggle");
const nav = document.querySelector(".nav");
if (toggle && nav) {
  toggle.addEventListener("click", () => nav.classList.toggle("is-open"));
  nav.querySelectorAll("a").forEach((a) =>
    a.addEventListener("click", () => nav.classList.remove("is-open"))
  );
}

document.querySelectorAll(".filter").forEach((btn) => {
  btn.addEventListener("click", () => {
    document.querySelectorAll(".filter").forEach((b) => b.classList.remove("is-on"));
    btn.classList.add("is-on");
    const f = btn.dataset.filter;
    document.querySelectorAll(".grid .card").forEach((card) => {
      card.classList.toggle("is-hidden", f !== "all" && card.dataset.cat !== f);
    });
  });
});

const lb = document.querySelector(".lb");
if (lb) {
  const lbImg = lb.querySelector("img");
  document.querySelectorAll(".grid .card").forEach((card) => {
    card.addEventListener("click", (e) => {
      e.preventDefault();
      lbImg.src = card.getAttribute("href");
      lbImg.alt = card.querySelector("img").alt;
      lb.classList.add("is-open");
    });
  });
  lb.addEventListener("click", () => lb.classList.remove("is-open"));
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape") lb.classList.remove("is-open");
  });
}

const slides = [...document.querySelectorAll(".slide")];
const dots = [...document.querySelectorAll(".dots button")];
if (slides.length) {
  let i = 0;
  let timer;
  const show = (n) => {
    i = (n + slides.length) % slides.length;
    slides.forEach((s, k) => s.classList.toggle("is-on", k === i));
    dots.forEach((d, k) => d.classList.toggle("is-on", k === i));
  };
  const play = () => {
    clearInterval(timer);
    timer = setInterval(() => show(i + 1), 5500);
  };
  dots.forEach((d, k) =>
    d.addEventListener("click", () => {
      show(k);
      play();
    })
  );
  const prev = document.querySelector(".hero-arrow.prev");
  const next = document.querySelector(".hero-arrow.next");
  if (prev) prev.addEventListener("click", () => { show(i - 1); play(); });
  if (next) next.addEventListener("click", () => { show(i + 1); play(); });
  const visual = document.querySelector(".hero-visual");
  if (visual) {
    visual.addEventListener("mouseenter", () => clearInterval(timer));
    visual.addEventListener("mouseleave", play);
  }
  play();
}
